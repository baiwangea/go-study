package main

import "fmt"

/*
═══════════════════════════════════════════════════════════════════════
L1-01：函数与返回值
═══════════════════════════════════════════════════════════════════════

【核心概念】
    函数 = 名字 + 参数表 + 返回值列表 + 函数体。
    Go 把「返回值类型」写在参数表的**后面**，而不是像 C/Java 那样写在前面：

        func plus(a, b int) int { return a + b }
        //      └─参数表─┘  └返回类型

    两个相邻参数类型相同时可以合并声明：a, b int 等价于 a int, b int。
    返回值不是必须接收的：Go 不强制你处理它（和 Java 的「忽略返回值也合法」一致，
    但和 Rust 的 #[must_use] 风格相反）。

【你会看到】
    ✓ plus(1, 2) 输出 3
    ✓ 丢弃返回值也能编译通过（不接收返回值的调用是合法语句）

【思考题】（动手改代码验证，别空想）
    1. func plus(a, b int) int 与 func plus(a int, b int) int 等价吗？漏写一个 int 会怎样？
    2. 调用 plus(1, 2) 却不接收返回值，Go 报错吗？和 Java/JS 有什么差别？

【通关标准】
    能口述返回类型的位置规则，并亲手验证两道思考题。

【前置】无（第一关）              【标签】参数 · 返回类型位置
═══════════════════════════════════════════════════════════════════════
*/

// plus 是最小的函数样例：两个 int 参数，返回它们的和。
// 注意 a, b int 这种「合并写法」——类型相同时只需写一次。
func plus(a, b int) int {
	return a + b
}

func main() {
	fmt.Println("\n=== L1-01 函数与返回值 ===")

	// ── 示例 1：调用函数并接收返回值 ─────────────────────────────────────
	fmt.Println("\n【示例 1】调用函数并接收返回值")
	fmt.Println("  1 + 2 =", plus(1, 2))

	// ── 示例 2：返回值可以丢弃 ───────────────────────────────────────────
	// 为什么能这样写？因为「函数调用」本身就是一个合法语句，
	// 它的返回值用不用由你决定，编译器不会拦你。
	fmt.Println("\n【示例 2】返回值可以丢弃")
	plus(1, 2) // 返回值可以直接丢弃，Go 不强制接收
	fmt.Println("  plus(1, 2) 被调用但结果丢弃 —— 编译通过（Go 不强制接收返回值）")

	// ── 关键总结 ─────────────────────────────────────────────────────────
	fmt.Println("\n【关键总结】")
	fmt.Println("  • 返回类型写在参数表后面：func f(a int) int")
	fmt.Println("  • 相邻同类型参数可合并：a, b int 等价于 a int, b int")
	fmt.Println("  • 返回值可以接收，也可以直接丢弃")
}
