package main

import "fmt"

/*
═══════════════════════════════════════════════════════════════════════
L1-03：变长参数 ...
═══════════════════════════════════════════════════════════════════════

【核心概念】
    参数表里写 nums ...int，表示「这里可以塞任意个 int」。
    关键：**在函数体内，nums 就是一个普通的 []int**，不用自己建切片。
    反过来，如果你手上已经有 []int，想把它喂给变长参数，
    必须写成 nums...（切片展开），否则类型对不上会编译失败。

    规则：变长参数只能有一个，且必须放在参数表最后。

【你会看到】
    ✓ 传 2 个与 4 个参数都能调用
    ✓ 切片用 nums... 展开后结果一致

【思考题】（动手改代码验证，别空想）
    1. 已有 []int{1,2,3}，直接 sum(nums) 会编译失败吗？为什么必须写 sum(nums...)？
    2. 变长参数必须放在参数表最后，试试 sum(prefix string, nums ...int, suffix string) 看报错。

【通关标准】
    能用 s... 展开传参，并说清函数内 nums 的类型。

【前置】L1-01              【标签】variadic · 切片展开
═══════════════════════════════════════════════════════════════════════
*/

// sum 演示变长参数：nums 在函数体内就是 []int。
// 返回 (个数, 合计) 两个值，顺便复用上一关的多返回值。
func sum(nums ...int) (int, int) {
	total := 0
	for _, n := range nums { // 能 range，正说明 nums 是个切片
		total += n
	}
	return len(nums), total
}

func main() {
	fmt.Println("\n=== L1-03 变长参数 ... ===")

	// ── 示例 1：直接塞两个实参 ───────────────────────────────────────────
	fmt.Println("\n【示例 1】直接传多个实参")
	count, total := sum(1, 2)
	fmt.Printf("  sum(1, 2)      → 个数 %d，合计 %d\n", count, total)

	// ── 示例 2：塞四个实参，同一函数照样能接 ─────────────────────────────
	fmt.Println("\n【示例 2】参数个数可变")
	count, total = sum(1, 2, 3, 4)
	fmt.Printf("  sum(1, 2, 3, 4) → 个数 %d，合计 %d\n", count, total)

	// ── 示例 3：把切片用 ... 展开传进去 ──────────────────────────────────
	// 为什么必须写 nums...？因为 sum 期望的是「一串 int」，
	// 而 nums 是「一个 []int」，nums... 才是把它摊平成那串 int。
	fmt.Println("\n【示例 3】切片展开传参")
	nums := []int{5, 6, 7}
	count, total = sum(nums...)
	fmt.Printf("  sum(nums...)    → 个数 %d，合计 %d（切片展开传参）\n", count, total)

	// ── 关键总结 ─────────────────────────────────────────────────────────
	fmt.Println("\n【关键总结】")
	fmt.Println("  • 函数内 nums 的类型就是 []int，可直接 range / len")
	fmt.Println("  • 传切片要展开：sum(nums...)；漏掉 ... 会编译失败")
	fmt.Println("  • 变长参数只能有一个，且必须放在参数表最后")
}
