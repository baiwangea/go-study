package main

import "fmt"

/*
═══════════════════════════════════════════════════════════════════════
L1-02：多返回值与 error
═══════════════════════════════════════════════════════════════════════

【核心概念】
    Go 的函数可以返回多个值，最常见的形状就是 (结果, error)：

        func divide(a, b float64) (float64, error)

    这不是「语法糖」，而是 Go 错误处理的**地基**：Go 没有 try/catch，
    出错就把 error 当普通返回值交回去，由调用方显式判断 if err != nil。
    约定：err 非 nil 时，其它返回值不可信（这里是零值 0）。

【你会看到】
    ✓ 正常除法打印结果，err 为 <nil>
    ✓ 除零打印 error，且第一个返回值为零值（0.00）

【思考题】（动手改代码验证，别空想）
    1. 为什么 Go 不用 try/catch，而把 error 当成普通返回值？两种风格差别在哪？
    2. 如果只返回 error 不返回结果（func do() error），和 (结果, error) 比哪种更好传参？

【通关标准】
    能不看资料写出一个返回 (int, error) 的函数，并正确处理 err != nil 分支。

【前置】L1-01              【标签】多返回值 · error 惯例
═══════════════════════════════════════════════════════════════════════
*/

// divide 是「(结果, error)」这一 Go 惯用形状的最小例子。
// 出错时不 panic，而是把错误作为第二个返回值交出去，让调用方自己决定怎么处理。
func divide(a, b float64) (float64, error) {
	if b == 0 {
		// 第一个返回值给零值 0；err 非 nil 时它没有意义
		return 0, fmt.Errorf("除数不能为 0")
	}
	return a / b, nil
}

func main() {
	fmt.Println("\n=== L1-02 多返回值与 error ===")

	// ── 示例 1：正常路径，err 为 nil ─────────────────────────────────────
	fmt.Println("\n【示例 1】正常除法：err 为 nil")
	v, err := divide(10, 3)
	fmt.Printf("  10 / 3 = %.2f, err = %v\n", v, err)

	// ── 示例 2：出错路径，先看 err 再信结果 ──────────────────────────────
	// 用 = 而不是 := 复用上面的 v/err，这是 Go 里非常常见的一行。
	fmt.Println("\n【示例 2】除零：err 非 nil，结果不可信")
	v, err = divide(10, 0)
	fmt.Printf("  10 / 0 = %.2f, err = %v\n", v, err)
	fmt.Println("  ↑ err 非 nil 时结果不可信，必须先看 err（这就是 Go 的 if err != nil）")

	// ── 关键总结 ─────────────────────────────────────────────────────────
	fmt.Println("\n【关键总结】")
	fmt.Println("  • 惯用形状：(结果, error)，error 放最后一个返回值")
	fmt.Println("  • 成功时 err == nil，失败时 err != nil 且结果为零值")
	fmt.Println("  • 调用方必须先判断 err，再使用其它返回值")
}
