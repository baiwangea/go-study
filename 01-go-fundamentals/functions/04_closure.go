package main

import "fmt"

/*
═══════════════════════════════════════════════════════════════════════
L1-04：闭包捕获变量
═══════════════════════════════════════════════════════════════════════

【核心概念】
    闭包 = 一个函数 + 它捕获的外部变量。
    关键点：闭包捕获的是**变量本身**（引用），不是创建那一刻的值快照。
    所以每次调用同一个闭包，那个变量都会在原来的基础上继续变。

    每次调用 intSeq() 都会新开一份独立的 i：
    两次调用得到的两个闭包，各持有自己的计数器，互不干扰。

【你会看到】
    ✓ 同一个闭包连续调用得到 1 2 3
    ✓ 新建闭包从 1 重新开始；再调老闭包则继续累加

【思考题】（动手改代码验证，别空想）
    1. nextInt 和 nextInt2 两个闭包会共享计数器吗？为什么？
    2. 把 i++ / return i 改成先 return i 再 i++ 会编译报错吗？输出如何变化？
    3. for 循环里创建闭包时捕获循环变量，Go 1.22 前后行为有什么不同？（进阶，可先记住结论）

【通关标准】
    能解释「共享 vs 独立」，并用两个闭包亲手验证。

【前置】L1-01              【标签】closure · 作用域
═══════════════════════════════════════════════════════════════════════
*/

// intSeq 返回一个「计数器闭包」。
// 每次调用 intSeq() 都会创建一份全新的 i，返回的匿名函数就一直持有它。
func intSeq() func() int {
	i := 0
	return func() int {
		i++ // 改的是外层那个 i —— 闭包持有的是变量，不是值
		return i
	}
}

func main() {
	fmt.Println("\n=== L1-04 闭包捕获变量 ===")

	// ── 示例 1：同一个闭包，状态持续累加 ─────────────────────────────────
	fmt.Println("\n【示例 1】同一个闭包：连续调用 1 2 3")
	nextInt := intSeq()
	fmt.Println("  同一个闭包：", nextInt(), nextInt(), nextInt())

	// ── 示例 2：新建闭包 = 新的独立计数器 ────────────────────────────────
	// 为什么是 1？因为 intSeq() 又执行了一次，产生了新的 i。
	fmt.Println("\n【示例 2】新建闭包：各自独立")
	nextInt2 := intSeq()
	fmt.Println("  新闭包重新计数：", nextInt2(), "（与 nextInt 互不影响，各自持有独立的 i）")
	fmt.Println("  再调老闭包：", nextInt(), "（它自己的 i 已经累加到 4）")

	// ── 关键总结 ─────────────────────────────────────────────────────────
	fmt.Println("\n【关键总结】")
	fmt.Println("  • 闭包捕获的是变量本身（引用），不是值快照")
	fmt.Println("  • 同一个闭包被多次调用，共享同一个变量")
	fmt.Println("  • 再次调用外层函数，会新开一份独立的变量")
}
