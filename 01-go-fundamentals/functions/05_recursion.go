package main

import "fmt"

/*
═══════════════════════════════════════════════════════════════════════
L1-05：递归与终止条件
═══════════════════════════════════════════════════════════════════════

【核心概念】
    递归 = 函数调用自己。三要素缺一不可：
        ① 终止条件（什么时候停）
        ② 递推关系（大问题怎么化小）
        ③ 返回值（每层把结果交回上一层）
    少了终止条件就是无限递归，运行时立刻 panic: stack overflow。
    每进入一层递归都要占一个栈帧，所以递归通常比 for 循环更「贵」。

【你会看到】
    ✓ fact(7) = 5040
    ✓ fact(0) 与 fact(1) 都等于 1（因为终止条件写的是 n <= 1）
    ✓ 把终止条件删掉会立刻栈溢出

【思考题】（动手改代码验证，别空想）
    1. 为什么 var fact func(int) int 要先声明再赋值？直接
       fact := func(n int) int { ... fact(n-1) } 为什么不行？
    2. 把 if n <= 1 分支删掉再运行，报什么错？（panic: stack overflow）
    3. 用 for 循环改写阶乘，性能差别在哪？（提示：每层递归都要一个栈帧）

【通关标准】
    能说出递归三要素（终止条件、递推、返回值），并解释栈溢出成因。

【前置】L1-02              【标签】recursion · 栈
═══════════════════════════════════════════════════════════════════════
*/

// fact 为什么写成「先 var 声明、再赋值匿名函数」，而不是直接 fact := func...？
// 因为匿名函数体里引用了 fact 自己，而 := 右侧在求值的那一刻 fact 还不存在，
// 编译器会直接报 undefined: fact。所以递归的匿名函数必须先有个名字。
var fact func(n int) int

func main() {
	fmt.Println("\n=== L1-05 递归与终止条件 ===")

	// 在这里把函数体补上：此时 fact 这个名字已经存在，函数体内才能引用自己。
	fact = func(n int) int {
		if n <= 1 { // ① 终止条件：n <= 1 时直接返回 1
			return 1
		}
		return n * fact(n-1) // ② 递推 + ③ 返回值：n! = n * (n-1)!
	}

	// ── 示例 1：从 0 到 7 跑一遍阶乘 ─────────────────────────────────────
	fmt.Println("\n【示例 1】fact(0) ~ fact(7)")
	for _, n := range []int{0, 1, 5, 7} {
		fmt.Printf("  fact(%d) = %d\n", n, fact(n))
	}
	fmt.Println("  ↑ 0! 与 1! 都等于 1，因为终止条件写的是 n <= 1")

	// ── 关键总结 ─────────────────────────────────────────────────────────
	fmt.Println("\n【关键总结】")
	fmt.Println("  • 递归三要素：终止条件、递推关系、返回值")
	fmt.Println("  • 终止条件缺失 → 无限递归 → panic: stack overflow")
	fmt.Println("  • 递归匿名函数要先声明名字，再赋值函数体")
}
