package main

import "fmt"

/*
═══════════════════════════════════════════════════════════════════════
L1-13：方法接收者 —— 值还是指针？
═══════════════════════════════════════════════════════════════════════

【核心概念】
    方法接收者写在 func 和方法名之间：func (c Counter) / func (c *Counter)。
    要改状态 → 指针接收者；只读小结构体 → 值接收者。
    同一个类型的方法集最好保持一致，别一半值一半指针。

【你会看到】
    ✓ IncValue 值接收者：连调三次都是 1 1 1 —— 每次都在改副本
    ✓ IncPtr 指针接收者：依次得到 1 2 3   —— 真正累加
    ✓ 值变量调指针方法、指针变量调值方法都能编译 —— Go 自动转换

【思考题】（动手改代码验证，别空想）
    1. 把 IncValue 的接收者改成 *Counter，c.IncValue() 还能编译吗？
       反过来把 IncPtr 改成值接收者，c.n 还会变吗？
    2. 为什么不建议一个类型「一半方法用值接收者、一半用指针接收者」？
    3. sync.Mutex 为什么绝对不能按值拷贝？（提示：看看本关的接收者规则）

【接收者选择规则】
    ✓ 需要修改接收者状态       → 指针
    ✓ 接收者很大（拷贝成本高） → 指针
    ✓ 类型里含 sync.Mutex 等   → 指针（必须）
    ✓ 小的、只读的结构体       → 值
    ✓ 一致性：只要有一个方法用了指针，其余也统一用指针

【通关标准】
    能说清「值接收者自增为什么永远返回 1」，
    并知道什么样的类型必须用指针接收者。

【前置】L1-12              【标签】方法接收者 · 方法集 · 自动取址/解引用
═══════════════════════════════════════════════════════════════════════
*/

// Counter 是一个计数器，用来对比两种接收者的行为差异。
type Counter struct {
	n int
}

// IncValue 是值接收者：c 是调用者的一份拷贝，改它不影响原对象。
func (c Counter) IncValue() int {
	c.n++ // 改的是副本里的 n
	return c.n
}

// IncPtr 是指针接收者：c 指向原对象，改的就是原对象。
func (c *Counter) IncPtr() int {
	c.n++ // 通过指针改到了原对象
	return c.n
}

// GetValue 只读，值接收者就够了。
func (c Counter) GetValue() int {
	return c.n
}

func main() {
	fmt.Println("\n=== L1-13 方法接收者：值 or 指针？ ===")

	// ── 示例 1：值接收者 —— 每次调用都拷贝一份接收者 ─────────────────────
	fmt.Println("\n【示例 1】值接收者：每次调用都从零开始")
	c := Counter{n: 0}
	fmt.Printf("  初始 c.n = %d\n", c.GetValue())

	fmt.Print("  连续调用 IncValue() 三次，返回值依次是：")
	for i := 0; i < 3; i++ {
		fmt.Printf("%d ", c.IncValue())
	}
	fmt.Println()
	fmt.Printf("  但 c.n 仍然是 %d ← 每次都改的是新副本，所以永远是 0+1=1\n", c.n)

	// ── 示例 2：指针接收者 —— 真正累加 ───────────────────────────────────
	fmt.Println("\n【示例 2】指针接收者：真正修改原对象")
	fmt.Print("  连续调用 IncPtr() 三次，返回值依次是：")
	for i := 0; i < 3; i++ {
		fmt.Printf("%d ", c.IncPtr()) // Go 自动转成 (&c).IncPtr()
	}
	fmt.Println()
	fmt.Printf("  c.n 现在是 %d ← 正常累加\n", c.n)

	// ── 示例 3：Go 的自动转换（语法糖） ──────────────────────────────────
	fmt.Println("\n【示例 3】Go 的自动转换")
	c2 := Counter{n: 100}
	c2.IncPtr() // 值变量调指针方法：Go 自动写成 (&c2).IncPtr()
	fmt.Printf("  值变量 c2 调用指针方法 → c2.n = %d\n", c2.n)

	c3 := &Counter{n: 200}
	val := c3.GetValue() // 指针变量调值方法：Go 自动写成 (*c3).GetValue()
	fmt.Printf("  指针变量 c3 调用值方法 → 返回 %d\n", val)
	fmt.Println("  ⚠️  自动转换只在「变量可寻址」时成立；map 里的元素不可寻址，调指针方法会编译失败")

	// ── 关键对比 ─────────────────────────────────────────────────────────
	fmt.Println("\n【关键对比】")
	fmt.Println("  值接收者   func (c Counter)")
	fmt.Println("    · 收到整个结构体的副本")
	fmt.Println("    · 修改不影响原对象，天然并发只读安全")
	fmt.Println("    · 适合小的、只读的操作")
	fmt.Println()
	fmt.Println("  指针接收者 func (c *Counter)")
	fmt.Println("    · 收到指向原对象的指针")
	fmt.Println("    · 可以修改原对象，也避免大结构体拷贝")
	fmt.Println("    · 必须用于：需要改状态、结构体大、类型里含 sync.Mutex")
}
